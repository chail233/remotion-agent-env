// scripts/07 build-vo-timeline.mjs — 把配音元数据排成场景时间轴，生成 TS 模块。
//
// 输入：public/vo/meta.json（scripts/06 gen-vo.mjs 产出）
// 输出：src/vo.ts（默认）
//   SCENES   每场起点/时长（含 lead/tail 留白与转场重叠）
//   VO_SEQ   每场配音的全局起点
//   CAPS     字幕 [起帧, 止帧, 文本]
//   WORDS    词级时间 [文本, 起帧, 止帧]（卡拉OK字幕）
//   BEATS    场景内节拍锚点（场景本地帧），由词级时间戳自动跟随配音
//
// 用法（项目根运行）：
//   node remotion-components/scripts/build-vo-timeline.mjs
//   node remotion-components/scripts/build-vo-timeline.mjs --meta public/vo/meta.json --out src/vo.ts
//
// 时间轴参数来自 vo/script.json 的每个 scene（gen-vo 原样带进 meta）：
//   lead        进入留白（帧，默认 26）
//   tail        收尾留白（帧，默认 46）
//   transition  与下一场的转场重叠（帧，默认 20；最后一场恒为 0）
//   beats       可选，{ "锚点名": ["词 token", 兜底秒数] }
// 场景时长 = lead + ceil(durSec × fps) + tail；下一场起点 = 本场起点 + 时长 − 转场重叠。

import fs from "node:fs";
import path from "node:path";

const ARGV = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = ARGV.indexOf(`--${name}`);
  return i >= 0 && ARGV[i + 1] && !ARGV[i + 1].startsWith("--") ? ARGV[i + 1] : fallback;
};
const fromCwd = (p) => path.resolve(process.cwd(), p);

const metaPath = fromCwd(opt("meta", "public/vo/meta.json"));
const outPath = fromCwd(opt("out", "src/vo.ts"));
const LEAD = 26;
const TAIL = 46;
const TRANSITION = 20;

let meta;
try {
  meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));
} catch (err) {
  console.error(`读不到配音元数据 ${metaPath}：${err.message}`);
  console.error("先运行 scripts/06 gen-vo.mjs");
  process.exit(1);
}
const FPS = meta.fps ?? 30;
const input = Array.isArray(meta.scenes) ? meta.scenes : [];
if (input.length === 0) {
  console.error("meta.json 里没有 scenes");
  process.exit(1);
}

// 1) 场景时长：配音帧数 + 首尾留白
const scenes = input.map((s) => {
  const lead = s.lead ?? LEAD;
  const tail = s.tail ?? TAIL;
  const voF = Math.ceil(s.durSec * FPS);
  return { ...s, lead, tail, voF, dur: lead + voF + tail };
});

// 2) 按转场重叠排起点
let cursor = 0;
const layout = scenes.map((s, i) => {
  const transition = i < scenes.length - 1 ? (s.transition ?? TRANSITION) : 0;
  const start = cursor;
  cursor = start + s.dur - transition;
  return { ...s, transition, start };
});
const total = layout[layout.length - 1].start + layout[layout.length - 1].dur;

// 3) 字幕 / 词级时间换算到全局帧
const caps = [];
const words = [];
const voSeq = [];
for (const s of layout) {
  const voFrom = s.start + s.lead;
  voSeq.push({ id: s.id, from: voFrom });
  for (const c of s.caps ?? []) {
    const from = voFrom + Math.floor(c.start * FPS);
    const to = voFrom + Math.ceil(c.end * FPS) + 6;
    caps.push([from, Math.max(from + 20, to), c.text]);
  }
  for (const w of s.words ?? []) {
    const from = voFrom + Math.floor(w.start * FPS);
    const to = voFrom + Math.ceil(w.end * FPS);
    words.push([w.t, from, Math.max(from + 2, to)]);
  }
}

// 4) 词级节拍锚点：先精确匹配 token，再退化为包含；找不到用兜底秒数
const beats = {};
for (const s of layout) {
  if (!s.beats) continue;
  const local = {};
  for (const [key, [token, fallbackSec]] of Object.entries(s.beats)) {
    const list = s.words ?? [];
    const exact = list.findIndex((w) => w.t === token);
    const partial = list.findIndex((w) => w.t.includes(token));
    const idx = exact >= 0 && partial >= 0 ? Math.min(exact, partial) : Math.max(exact, partial);
    const sec = idx >= 0 ? list[idx].start : fallbackSec;
    local[key] = s.lead + Math.round(sec * FPS);
  }
  beats[s.id] = local;
}

// 5) 生成模块
const sceneDefs = layout.map(({ id, title, start, dur, lead, tail, voF }) => ({
  id,
  title,
  start,
  dur,
  lead,
  tail,
  voF,
}));
const header = `// AUTO-GENERATED by remotion-components/scripts/build-vo-timeline.mjs — 不要手改。
// 输入 ${path.relative(process.cwd(), metaPath)}；改词后重跑 gen-vo.mjs + build-vo-timeline.mjs。
export const FPS = ${FPS};
export const TOTAL = ${total};
export interface SceneDef {
  id: string;
  title: string;
  start: number;
  dur: number;
  lead: number;
  tail: number;
  voF: number;
}
export const SCENES: SceneDef[] = ${JSON.stringify(sceneDefs, null, 1)};
export const VO_SEQ: { id: string; from: number }[] = ${JSON.stringify(voSeq, null, 1)};
export type Cap = [number, number, string];
export const CAPS: Cap[] = ${JSON.stringify(caps, null, 1)};
/** 词级时间（全局帧）：[文本, 起, 止]，供 Karaoke 字幕。 */
export const WORDS: [string, number, number][] = ${JSON.stringify(words, null, 1)};
/** 场景节拍（场景本地帧）：锚点在词级时间戳上，换配音自动跟随。 */
export const BEATS: Record<string, Record<string, number>> = ${JSON.stringify(beats, null, 1)};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, header);

console.log(`TOTAL ${total} frames = ${(total / FPS).toFixed(1)}s  (${layout.length} scenes)`);
for (const s of layout) {
  console.log(
    `${s.id.padEnd(4)} start=${String(s.start).padStart(5)}  dur=${String(s.dur).padStart(4)}  ` +
      `vo=${String(s.voF).padStart(4)}  (${(s.dur / FPS).toFixed(1)}s)`,
  );
}
console.log(`\n时间轴 → ${path.relative(process.cwd(), outPath)}`);
